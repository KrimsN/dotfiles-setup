#!/usr/bin/env bash
# Запись фактов о том, ЧТО именно install.sh изменил на машине.
# Не запускать напрямую — подключать через `source` после
# scripts/lib/log.sh.
#
# Публичные точки входа: state::record, state::read, state::forget
#
# Зачем нужен отдельный слой. Почти всё, что делает install.sh, можно
# отменить, посмотрев на систему: файл с маркером ".knrc" — наш, бэкап
# рядом — наш, блок `# >>> knrc:... >>>` в rc-файле — наш. Но есть
# изменения, которые не оставляют следа, отличающего "было до нас" от
# "сделали мы":
#
#   - login-shell пользователя (`chsh -s zsh`) — по факту в passwd
#     видно только то, что сейчас стоит zsh; стоял ли он там до
#     install.sh, из системы уже не узнать;
#   - членство в группе docker (`usermod -aG docker`) — ровно та же
#     история.
#
# Без записи прежнего значения `knrc uninstall` может либо не трогать
# такие вещи вовсе (и оставить машину недоочищенной), либо угадывать
# (и сломать окружение пользователю, у которого zsh стоял и до нас).
# Поэтому: модуль, который делает необратимо-неотличимое изменение,
# записывает прежнее состояние сюда, а uninstall откатывает ТОЛЬКО то,
# что здесь записано.
#
# Формат сознательно примитивный — один факт = один файл с одной
# строкой. Ни парсинга, ни блокировок, ни схемы: файлов единицы,
# читать их должен уметь и человек `cat`-ом при разборе, почему
# uninstall повёл себя так, а не иначе.

set -euo pipefail

KNRC_STATE_DIR="${DOTFILES_STATE_DIR:-$HOME/.config/knrc}/state"

# state::record <name> <value> — запомнить факт. Перезаписывает уже
# записанное: повторный запуск install.sh на машине, где мы уже
# что-то меняли, не должен затирать ПЕРВОЕ (настоящее прежнее)
# значение — поэтому вызывающий обязан звать record только в той ветке,
# где изменение реально происходит (см. zsh::configure_shell).
state::record() {
  local name="$1" value="$2"

  if [ "${DRY_RUN:-0}" = "1" ]; then
    log::info "[dry-run] запомнил бы состояние $name=$value"
    return 0
  fi

  mkdir -p "$KNRC_STATE_DIR"
  printf '%s\n' "$value" > "$KNRC_STATE_DIR/$name"
}

# state::read <name> — напечатать значение; код возврата 1, если факт
# не записан (машина настроена версией без записи состояния, либо
# изменение не делалось).
state::read() {
  local file="$KNRC_STATE_DIR/$1"
  [ -f "$file" ] || return 1
  head -n1 "$file"
}

# state::forget <name> — забыть факт (после успешного отката).
state::forget() {
  rm -f "$KNRC_STATE_DIR/$1"
}

if [ "${BASH_SOURCE[0]}" = "${0}" ]; then
  echo "scripts/lib/state.sh: подключать через source, не запускать напрямую" >&2
  exit 1
fi
