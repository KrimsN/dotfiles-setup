#!/usr/bin/env bash
# Цветной вывод для сообщений самого скрипта (не путать с "сырым"
# выводом вызываемых команд — apt-get/dnf/curl/git и т.п. — он остаётся
# нейтральным). Цель: сообщения install.sh и модулей должны быть видны
# с первого взгляда в потоке лога установки.
# Не запускать напрямую — подключать через `source`.
#
# log::info <msg>  — обычное сообщение о прогрессе (bold cyan, stdout)
# log::warn <msg>  — некритичное предупреждение / пропуск (bold yellow, stderr)
# log::err  <msg>  — ошибка (bold red, stderr)
#
# Отключается автоматически, если вывод не терминал (например
# перенаправлен в файл/CI) или задана переменная NO_COLOR.
#
# Помимо цвета каждая строка получает фиксированный префикс
# "[.knrc] ▶/⚠/✖" — некоторые из вызываемых команд (get.docker.com,
# ohmyzsh installer и т.п.) тоже красят свой вывод, так что один только
# цвет не всегда отличает наше сообщение от чужого; префикс отличает
# всегда, даже если цвет отключён (NO_COLOR / не терминал). "[.knrc]" в
# квадратных скобках — чтобы взгляд цеплялся за строку целиком, а не
# терялся среди остального цветного текста в логе.

set -euo pipefail

LOG_TAG="[.knrc]"

if [ -z "${NO_COLOR:-}" ] && [ -t 1 ]; then
  LOG_CYAN=$'\033[1;36m'
  LOG_YELLOW=$'\033[1;33m'
  LOG_RED=$'\033[1;31m'
  LOG_RESET=$'\033[0m'
else
  LOG_CYAN="" LOG_YELLOW="" LOG_RED="" LOG_RESET=""
fi

log::info() {
  echo "${LOG_CYAN}${LOG_TAG} ▶ ${1}${LOG_RESET}"
}

log::warn() {
  echo "${LOG_YELLOW}${LOG_TAG} ⚠ ${1}${LOG_RESET}" >&2
}

log::err() {
  echo "${LOG_RED}${LOG_TAG} ✖ ${1}${LOG_RESET}" >&2
}

if [ "${BASH_SOURCE[0]}" = "${0}" ]; then
  echo "scripts/lib/log.sh: подключать через source, не запускать напрямую" >&2
  exit 1
fi
